function leerAlmacen(storage) {
  try {
    return storage?.getItem(CLAVE) ?? null;
  } catch {
    return null;
  }
}

// Idioma guardado. Si no hay nada guardado, o el valor no es un idioma válido, es español.
export function leerIdioma(storage = globalThis.localStorage) {
  const guardado = leerAlmacen(storage);
  return IDIOMAS.includes(guardado) ? guardado : IDIOMA_POR_DEFECTO;
}

export function guardarIdioma(idioma, storage = globalThis.localStorage) {
  try {
    storage?.setItem(CLAVE, idioma);
  } catch {
    // Sin almacenamiento (modo privado, bloqueado) el idioma vale para esta sesión.
  }
}

// Texto de una clave en un idioma. Las variables {nombre} se sustituyen por sus valores.
// Una clave que no existe se devuelve tal cual, para verla en pantalla y corregirla.
export function traducir(idioma, clave, variables = {}) {
  const texto = TEXTOS[idioma]?.[clave] ?? TEXTOS[IDIOMA_POR_DEFECTO][clave] ?? clave;
  return texto.replace(/\{(\w+)\}/g, (coincidencia, nombre) => (nombre in variables ? String(variables[nombre]) : coincidencia));
}

// Idioma actual de la app. Se lee una vez al cargar el módulo y cambia con cambiarIdioma().
let actual = leerIdioma();
const oyentes = new Set();

export function idiomaActual() {
  return actual;
}

// Texto en el idioma actual: lo usan las pantallas al dibujarse.
export function t(clave, variables) {
  return traducir(actual, clave, variables);
}

// Cambia el idioma, lo guarda y avisa a quien muestre textos fuera de la pantalla de Preact.
export function cambiarIdioma(idioma) {
  if (!IDIOMAS.includes(idioma)) throw new Error(`Idioma no soportado: ${idioma}`);
  actual = idioma;
  guardarIdioma(idioma);
  for (const avisar of oyentes) avisar(idioma);
}

export function alCambiarIdioma(oyente) {
  oyentes.add(oyente);
  return () => oyentes.delete(oyente);
}
